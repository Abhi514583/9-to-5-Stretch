export function getRoutineBySlug(slug: string): Routine | undefined {
  return routines.find((routine) => routine.slug === slug);
}

export function getRoutinesByCategory(category: RoutineCategory): Routine[] {
  return routines.filter((routine) => routine.category === category);
}

export function getTotalRoutineSeconds(routine: Routine): number {
  return routine.steps.reduce((total, step) => total + step.seconds, 0);
}

export function getRoutineDurationLabel(routine: Routine): string {
  return `${routine.durationMinutes} min`;
}

